# Type alias: (advance_u, list of stroke point lists)
RawGlyph = tuple[int, list[list[tuple[int, int]]]]


def _arc(cx: float, cy: float, rx: float, ry: float, a0: float, a1: float, steps: int = 10) -> list[tuple[int, int]]:
    pts: list[tuple[int, int]] = []
    for i in range(steps + 1):
        t = a0 + (a1 - a0) * (i / steps)
        x = int(round(max(0, min(1000, cx + rx * math.cos(t)))))
        y = int(round(max(0, min(1000, cy + ry * math.sin(t)))))
        pts.append((x, y))
    return pts


