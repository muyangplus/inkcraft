def _procedural_cjk_fallback(ch: str) -> tuple[int, list[np.ndarray]]:
    """Deterministic calligraphic single-line glyph synthesis for unseen CJK/Unicode chars.

    Produces visually coherent 4-6 stroke Chinese-like balanced single-line geometry rather
    than empty gaps so any arbitrary Chinese document renders smoothly even before Colab build.
    """
    digest = hashlib.sha256(ch.encode("utf-8")).digest()
    strokes: list[np.ndarray] = []

    # Top horizontal stroke
    y1 = 190 + (digest[0] % 70)
    strokes.append(np.array([[180 + (digest[1] % 60), y1], [820 - (digest[2] % 60), y1 - 15]], dtype=np.int16))

    # Central vertical or box structure
    if digest[3] & 1:
        # Left-right balanced radical + right element
        vx = 300 + (digest[4] % 60)
        strokes.append(np.array([[vx, y1], [vx, 820]], dtype=np.int16))
        strokes.append(np.array([[170, 440], [420, 425]], dtype=np.int16))
        rx0, rx1 = 500, 830
        ry0, ry1 = 300 + (digest[5] % 70), 790
        strokes.append(np.array([[rx0, ry0], [rx1, ry0 - 10], [rx1 - 20, ry1]], dtype=np.int16))
        strokes.append(np.array([[rx0 + 15, (ry0 + ry1) // 2], [rx1 - 20, (ry0 + ry1) // 2 - 10]], dtype=np.int16))
        strokes.append(np.array([[rx0, ry0], [rx0 + 15, ry1], [rx1 - 20, ry1 - 10]], dtype=np.int16))
    else:
        # Top-bottom balanced structure
        strokes.append(np.array([[500, 145], [500, 845]], dtype=np.int16))
        mid_y = 475 + (digest[6] % 55)
        strokes.append(np.array([[220, mid_y], [780, mid_y - 12]], dtype=np.int16))
        strokes.append(np.array([[480, mid_y], [210, 825]], dtype=np.int16))
        strokes.append(np.array([[520, mid_y], [810, 825]], dtype=np.int16))
        if digest[7] & 1:
            strokes.append(np.array([[150, 815], [850, 800]], dtype=np.int16))

    return 1000, strokes


def get_fallback_glyph(ch: str) -> tuple[int, list[np.ndarray], bool]:
    """Return `(advance_u, strokes, is_exact_builtin)` for any character.

    `is_exact_builtin` is True when the character exists in BUILTIN_GLYPHS,
    False when procedurally synthesized.
    """
    if not ch:
        return 360, [], True
    c = ch[0]
    if c in BUILTIN_GLYPHS:
        adv, raw_strokes = BUILTIN_GLYPHS[c]
        return adv, [np.asarray(s, dtype=np.int16) for s in raw_strokes], True
    adv, strokes = _procedural_cjk_fallback(c)
    return adv, strokes, False
