<#
.SYNOPSIS
  Handwrite Studio - Optional Windows RTX 4070 Super (12GB) MinerU Pipeline GPU Installer
.DESCRIPTION
  Creates an isolated runtime\mineru-venv with PyTorch CUDA 12.4 and MinerU `pipeline` backend
  (strictly avoiding vLLM/sglang to stay <= 8.5GB VRAM on 12GB cards) and writes .env.
#>
param(
    [switch]$UseChinaMirror
)

$ErrorActionPreference = "Stop"
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$Root = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
Set-Location $Root

Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "  MinerU Pipeline GPU 环境安装 (适配 RTX 4070 Super 12GB)" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan

$uvCmd = Get-Command uv -ErrorAction SilentlyContinue
if (-not $uvCmd) {
    $env:Path = "$env:USERPROFILE\.local\bin;$env:USERPROFILE\.cargo\bin;$env:Path"
    $uvCmd = Get-Command uv -ErrorAction SilentlyContinue
}
if (-not $uvCmd) {
    throw "请先运行「安装Windows环境.bat」以安装 uv 与基础环境。"
}

$mineruVenv = Join-Path $Root "runtime\mineru-venv"
$mineruPy = Join-Path $mineruVenv "Scripts\python.exe"
$mineruExe = Join-Path $mineruVenv "Scripts\mineru.exe"

Write-Host "`n[1/3] 创建隔离 MinerU 虚拟环境: $mineruVenv" -ForegroundColor Cyan
uv venv $mineruVenv --python 3.12

Write-Host "`n[2/3] 安装 PyTorch CUDA 12.4 与 MinerU Pipeline（不含 vLLM）..." -ForegroundColor Cyan
uv pip install --python $mineruPy torch torchvision --index-url https://download.pytorch.org/whl/cu124

$mineruArgs = @("pip", "install", "--python", $mineruPy, "mineru[pipeline]")
if ($UseChinaMirror) {
    $mineruArgs += @("--index-url", "https://pypi.tuna.tsinghua.edu.cn/simple")
}
& uv @mineruArgs

Write-Host "`n[3/3] 写入根目录 .env 显存保护配置 (MINERU_VIRTUAL_VRAM_SIZE=8)..." -ForegroundColor Cyan
$envFile = Join-Path $Root ".env"
$envLines = @(
    "# Auto-generated by install_mineru_gpu_windows.ps1",
    "MINERU_BACKEND=pipeline",
    "MINERU_DEVICE_MODE=cuda",
    "MINERU_VIRTUAL_VRAM_SIZE=8",
    "MINERU_MODEL_SOURCE=modelscope",
    "MINERU_CHUNK_PAGES=10",
    "MINERU_MAX_DPI=200",
    "MINERU_BIN=$mineruExe",
    "INKCRAFT_MINERU_PYTHON=$mineruPy"
)
Set-Content -Path $envFile -Value ($envLines -join "`r`n") -Encoding UTF8

& $mineruPy -c "import torch; print('[OK] CUDA available:', torch.cuda.is_available(), torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'CPU')"
Write-Host "`n[完成] MinerU Pipeline GPU 环境已就绪！重启「启动墨迹工坊.bat」即可自动启用。" -ForegroundColor Green
